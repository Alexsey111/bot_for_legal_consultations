"""Подбор порога релевантности: где кончается «мой» вопрос и начинается «не мой».

Считаем максимальный косинус по top-5 для двух групп вопросов.
Chroma лежит в L2-пространстве, векторы единичные, поэтому cos = 1 - dist/2.
"""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "tools"))
import qa_boot  # noqa: F401

from rag_engine import get_rag_engine

ON = [
    "что такое договор дарения",
    "какой срок исковой давности",
    "можно ли расторгнуть договор аренды досрочно",
    "что такое договор займа",
    "что такое неустойка",
    "что такое договор купли-продажи",
    "как оформить доверенность",
    "что такое сервитут",
    "ответственность за вред от источника повышенной опасности",
    "что такое публичный договор",
    "наём жилого помещения права нанимателя",
    "возмещение вреда имуществу",
    "как делится наследство по закону",
    "что такое залог и ипотека",
    "как заключить брак и что регулирует семейный кодекс",
    "какие бывают юридические лица",
    "что такое оферта и акцепт",
    "как взыскать долг по расписке",
]

OFF = [
    "как приготовить борщ",
    "какая погода завтра в Барнауле",
    "кто выиграл чемпионат мира по футболу",
    "кража",
    "дело Иванова",
    "напиши код на питоне для сортировки списка",
    "как настроить роутер",
    "что такое любовь",
    "сколько стоит билет в Москву",
    "посоветуй фильм на вечер",
    "как похудеть за месяц",
    "что делать если болит голова",
]

rag = get_rag_engine()
db = rag.db


def top_cos(q, k=5):
    res = db.vector_db.similarity_search_with_score(q, k=k)
    return max(1.0 - sc / 2.0 for _, sc in res)


rows = []
for label, qs in (("МОЙ", ON), ("НЕ МОЙ", OFF)):
    print(f"\n--- {label} ---")
    for q in qs:
        c = top_cos(q)
        rows.append((label, c, q))
        print(f"    {c:.3f}  {q}")

on = sorted(c for lab, c, _ in rows if lab == "МОЙ")
off = sorted(c for lab, c, _ in rows if lab == "НЕ МОЙ")
print(f"\nМОЙ:    min={on[0]:.3f}  медиана={on[len(on)//2]:.3f}  max={on[-1]:.3f}")
print(f"НЕ МОЙ: min={off[0]:.3f}  медиана={off[len(off)//2]:.3f}  max={off[-1]:.3f}")
print("\nсамые «похожие на право» вопросы не по теме:", [f'{c:.3f} {q}' for lab, c, q in rows if lab == "НЕ МОЙ"][-3:])
print("самые «слабые» свои вопросы:", [f'{c:.3f} {q}' for lab, c, q in rows if lab == "МОЙ"][:3])
